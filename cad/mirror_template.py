#!/usr/bin/env python3
"""1:1 cutting template for the mirror blanks.

Run:  python3 cad/mirror_template.py

Every dimension comes from the same Scope the printed parts do, so the
template cannot drift out of step with the tube it has to fit.

One blank per sheet. At this length a blank needs 256.7 mm of factory edge and
the tiles are 298.45 mm, so only one fits per edge anyway — print the sheet
once and use it three times against three different edges.

The leading edge is a factory edge of the tile and is never cut. That is the
one optically critical edge: it lands on its neighbour at the seam and its
coating has to run right to it. The overlap edge is buried in dead space and
only needs to be burr-free; the two ends hide under the caps.
"""

from __future__ import annotations

import math
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from scope import Scope

TILE = 11.75 * 25.4          # the "unbreakable" mirror tiles, 298.45 mm


def blank_on_edge(scope: Scope):
    """Blank vertices rotated so the leading edge lies along y = 0.

    Returns (A, B, C, D): A and D on the factory edge, B and C inboard.
    """
    h, wn, ww = scope.blank_height, scope.blank_width(0), scope.blank_width(scope.length)
    a, b = (-wn / 2, 0.0), (wn / 2, 0.0)
    c, d = (ww / 2, h), (-ww / 2, h)

    u = ((d[0] - a[0]) / scope.blank_leg, (d[1] - a[1]) / scope.blank_leg)
    n = (u[1], -u[0])

    def to_edge(p):
        v = (p[0] - a[0], p[1] - a[1])
        return (v[0] * u[0] + v[1] * u[1], v[0] * n[0] + v[1] * n[1])

    pts = [to_edge(p) for p in (a, b, c, d)]
    shift = -min(p[0] for p in pts)
    return [(p[0] + shift, p[1]) for p in pts]


def tikz(scope: Scope, pts, ext: float = 4.0) -> str:
    """The blank at 1:1. Picture coordinates start at 0 — the page margin does
    the offsetting, and adding a second one here pushed the drawing off the
    paper the first time."""
    A, B, C, D = pts
    o = 0.0
    P = lambda p: f"({p[0] + o:.4f},{p[1]:.4f})"
    span = D[0] - 0.0
    parts = []
    add = parts.append

    add(r"\begin{tikzpicture}[x=1mm,y=1mm,line width=0.30mm]")

    # the blank
    add(rf"  \draw {P(A)} -- {P(B)} -- {P(C)} -- {P(D)} -- cycle;")
    for p in (A, B, C, D):
        add(rf"  \cmark{{{p[0] + o:.4f}}}{{{p[1]:.4f}}}")

    # factory-edge reference line, running past both ends
    add(rf"  \draw[fac,line width=0.7mm] ({o - ext:.2f},0) -- ({o + span + ext:.2f},0);")
    add(rf"  \foreach \x in {{{o - ext + 2:.0f},{o - ext + 6:.0f},...,{o + span + ext - 1:.0f}}} "
        r"{ \draw[fac!40,line width=0.15mm] (\x,0) -- ({\x-3},-3.2); }")
    add(rf"  \node[fac,font=\scriptsize\bfseries,below right] at ({o - ext:.2f},-4.6)"
        r" {FACTORY EDGE OF THE TILE — lay this line on it. Never cut or sand along it.};")
    add(rf"  \node[reg,font=\scriptsize,below right] at ({o - ext:.2f},-9.4)"
        r" {Everything below the line hangs off the tile, which is how you sight the alignment.};")

    # edge roles
    mid = lambda p, q: ((p[0] + q[0]) / 2 + o, (p[1] + q[1]) / 2)
    ang = math.degrees(math.atan2(C[1] - B[1], C[0] - B[0]))
    mx, my = mid(B, C)
    add(rf"  \node[font=\scriptsize,reg,rotate={ang:.2f}] at ({mx:.2f},{my + 3.4:.2f})"
        r" {overlap edge — cut, buried behind the next mirror};")
    add(rf"  \node[font=\scriptsize,fac] at ({(A[0] + D[0]) / 2 + o:.2f},3.4)"
        r" {leading edge — factory, uncut, coating right to the edge};")
    add(rf"  \node[font=\scriptsize,reg,rotate=90] at ({A[0] + o + 6:.2f},14)"
        r" {narrow end};")
    add(rf"  \node[font=\scriptsize,reg,rotate=90] at ({D[0] + o - 7:.2f},26)"
        r" {wide end};")
    add(r"\end{tikzpicture}")
    return "\n".join(parts)


