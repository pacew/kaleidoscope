TAIL = r"""
\vspace{3mm}
\hrule
\vspace{1.5mm}
{\footnotesize
__DIMS__

\smallskip

\textbf{Placing it.} Leave the protective film on. Lay the sheet so the heavy line sits on
a factory edge, with the strip below it overhanging so you can sight the alignment, and tape
it down. Prick through the centre of the four circled marks, lift the paper, join the pricks
with your straightedge, and cut only the three non-factory edges.

\smallskip

\textbf{Coated side up.} These are rear-surface mirrors. A jeweller's saw cuts on the
downstroke, so the teeth enter the top face and break out of the bottom; coated side up puts
that breakout on the clear face. Blade: a \#2, teeth pointing toward the handle.

\smallskip

\textbf{Mark the factory edge} on the coated back as soon as the blank is free. Once the
other three edges are cut it is easy to lose track of which one it was, and at assembly it
has to end up on the corner-block side of its plate.

\smallskip

\textbf{Width is forgiving, and not in the way you would guess.} Each mirror is pushed until
its leading edge stops against its neighbour, so \emph{that} edge lands on the vertex whatever
the blank measures. Width only sets how much surplus buries itself behind the next mirror.
__WINDOW__ across the narrow edge will seat. Too wide is the direction that fights you --- past
the limit the surplus runs out of dead space and jams against the neighbouring plate. Too narrow
only costs you: with no surplus left, the next mirror's leading edge has nothing to land on and
the seam shows as a dark line. So if you are going to miss, miss narrow.

\smallskip

\textbf{Sanding.} Only the cut edges, never the factory edge: 400-grit silicon carbide to take
the burr off, 600 to finish.
}
\end{document}
"""


def main():
    scope = Scope()
    pts = blank_on_edge(scope)
    A, B, C, D = pts
    span, depth = D[0], max(p[1] for p in pts)

    # Against the AS-BUILT optical face, not the nominal one. The stock runs
    # thicker than 1/16 in, so the face the mirrors actually form is 0.32 mm
    # narrower than the design number and the whole window shifts with it.
    face = scope.blank_width(0) - scope.mirror_overlap
    lo = face + 0.05
    hi = face + scope.overlap_limit
    dims = (rf"\textbf{{Blank:}} parallel edges \textbf{{{scope.blank_width(0):.2f}}} and "
            rf"\textbf{{{scope.blank_width(scope.length):.2f}\,mm}}, both slanted edges "
            rf"\textbf{{{scope.blank_leg:.2f}\,mm}}, height between the parallel edges "
            rf"\textbf{{{scope.blank_height:.2f}\,mm}}. Needs {span:.1f}\,mm of factory edge "
            rf"against a {TILE:.2f}\,mm tile, so one blank per edge --- three edges, or "
            rf"three tiles.")
    window = rf"Anything from {lo:.1f} to {hi:.1f}\,mm"

    # Centre the drawing on the paper. It is wider than the text block, so it
    # has to be pulled out of the left margin by hand.
    ext = 4.0
    pic = span + 2 * ext
    pull = 12.0 - (279.4 - pic) / 2

    tex = (HEAD.replace("__SUB__", f"{scope.length:.0f} mm scope")
           .replace("__PULL__", rf"\hspace*{{-{pull:.2f}mm}}")
           + tikz(scope, pts, ext)
           + TAIL.replace("__DIMS__", dims).replace("__WINDOW__", window))

    out = Path("mirror-template.tex")
    out.write_text(tex)
    r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", str(out)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit("pdflatex failed:\n" + r.stdout[-2000:])
    for junk in ("mirror-template.aux", "mirror-template.log"):
        Path(junk).unlink(missing_ok=True)

    print(f"scope      {scope.summary()}")
    print(f"blank      {scope.blank_width(0):.2f} / {scope.blank_width(scope.length):.2f} mm "
          f"parallel, legs {scope.blank_leg:.2f}, height {scope.blank_height:.2f}")
    print(f"on edge    {span:.2f} mm along the factory edge, {depth:.2f} mm in")
    print(f"tile       {TILE:.2f} mm edge -> {int(TILE // span)} blank per edge, "
          f"{'fits' if scope.blank_leg < TILE else 'LEG TOO LONG FOR A FACTORY EDGE'}")
    print(f"paper      drawing {pic:.1f} mm wide, centred -> "
          f"{(279.4 - pic) / 2:.1f} mm clear of each paper edge")
    print(f"window     {lo:.1f} to {hi:.1f} mm across the narrow edge")
    print(f"wrote      mirror-template.tex, mirror-template.pdf")


if __name__ == "__main__":
    main()
